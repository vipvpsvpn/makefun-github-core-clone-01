export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * Every object reachable from `roots`: commit -> tree + parents, tree -> entries
 * (gitlinks skipped), tag -> its target, blob -> nothing. Throws on a missing
 * object unless `allowMissing` is set.
 */
export function collectReachable(roots: Iterable<string>, lookup: ObjectLookup, allowMissing = false): Set<string> {
  const seen = new Set<string>();
  const queue: string[] = [];
  for (const root of roots) if (isOid(root)) queue.push(root);
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) {
      if (allowMissing) continue;
      throw new Error(`object ${oid} is missing from the store`);
    }
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      queue.push(commit.tree);
      for (const parent of commit.parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push(entry.oid);
      }
    }
  }
  return seen;
}

/**
 * BFS from `roots` following commit parents, recording each commit's generation
 * (0 = a root). Returns the commits at each generation up to `maxDepth`
 * generations (exclusive): with maxDepth 1, only the roots.
 */
export function commitsByGeneration(roots: string[], lookup: ObjectLookup, maxDepth: number): Map<string, number> {
  const gen = new Map<string, number>();
  const queue: string[] = [];
  for (const r of roots) {
    if (isOid(r) && !gen.has(r)) { gen.set(r, 0); queue.push(r); }
  }
  let head = 0;
  while (head < queue.length) {
    const oid = queue[head++];
    const g = gen.get(oid)!;
    if (g + 1 >= maxDepth) continue;
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) {
      if (!gen.has(parent)) { gen.set(parent, g + 1); queue.push(parent); }
    }
  }
  return gen;
}

/** Whether `ancestor` is reachable from `tip` following commit parents. */
export function isAncestor(ancestor: string, tip: string, lookup: ObjectLookup): boolean {
  if (ancestor === tip) return true;
  const seen = new Set<string>();
  const queue = [tip];
  while (queue.length) {
    const oid = queue.pop()!;
    if (oid === ancestor) return true;
    if (seen.has(oid)) continue;
    seen.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  return false;
}

/** The merge-base of two tips: the closest common ancestor to `baseTip`. */
export function mergeBase(headTip: string, baseTip: string, lookup: ObjectLookup): string | null {
  const headAncestors = new Set<string>();
  const queue = [headTip];
  while (queue.length) {
    const oid = queue.pop()!;
    if (headAncestors.has(oid)) continue;
    headAncestors.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  const bq = [baseTip];
  const bseen = new Set<string>();
  while (bq.length) {
    const oid = bq.shift()!;
    if (headAncestors.has(oid)) return oid;
    if (bseen.has(oid)) continue;
    bseen.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) bq.push(parent);
  }
  return null;
}

/** Flatten a tree object into path -> {mode, oid}, recursively. */
export function flattenTree(treeOid: string, lookup: ObjectLookup, out = new Map<string, { mode: string; oid: string }>(), prefix = ''): Map<string, { mode: string; oid: string }> {
  const object = lookup(treeOid);
  if (!object || object.type !== 'tree') return out;
  for (const entry of parseTree(object.data)) {
    const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.mode === '40000') flattenTree(entry.oid, lookup, out, path);
    else if (entry.mode !== '160000') out.set(path, { mode: entry.mode, oid: entry.oid });
  }
  return out;
}

/**
 * Build nested tree objects from a flat path map, writing each new tree object
 * through `put` (which stores it and returns its oid). Returns the root tree oid.
 */
export function buildTreeFromMap(
  files: Map<string, { mode: string; oid: string }>,
  put: (type: GitObjectType, data: Buffer) => string,
): string {
  interface Node { files: Map<string, { mode: string; oid: string }>; dirs: Map<string, Node> }
  const make = (): Node => ({ files: new Map(), dirs: new Map() });
  const root = make();
  for (const [path, entry] of files) {
    const segments = path.split('/');
    let node = root;
    for (let i = 0; i < segments.length - 1; i += 1) {
      const name = segments[i]!;
      if (!node.dirs.has(name)) node.dirs.set(name, make());
      node = node.dirs.get(name)!;
    }
    node.files.set(segments[segments.length - 1]!, entry);
  }
  const build = (node: Node): string => {
    const entries: TreeEntry[] = [];
    for (const [name, entry] of node.files) entries.push({ mode: entry.mode, name, oid: entry.oid });
    for (const [name, child] of node.dirs) entries.push({ mode: '40000', name, oid: build(child) });
    return put('tree', buildTree(entries));
  };
  return build(root);
}

// -------------------------------------------------------------------------------------------
// base64 / text
// -------------------------------------------------------------------------------------------

export function b64encode(buf: Buffer): string {
  return buf.toString('base64');
}

export function b64decode(text: string): Buffer {
  return Buffer.from(text.replace(/[\r\n\t ]+/g, ''), 'base64');
}

/** Parse an "author Name <email> ts tz" line into its parts. */
export function parseIdent(line: string): { name: string; email: string; timestamp: number; timezone: string } {
  const m = /^(.*) <([^>]*)> (\d+) ([+-]\d{4})$/.exec(line);
  if (!m) return { name: line, email: '', timestamp: 0, timezone: '+0000' };
  return { name: m[1]!, email: m[2]!, timestamp: Number(m[3]), timezone: m[4]! };
}
